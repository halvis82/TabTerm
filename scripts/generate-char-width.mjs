#!/usr/bin/env node
// Regenerate the width corrections that carry xterm's table from Unicode 11 to the current one.
//
//   node scripts/generate-char-width.mjs
//
// A terminal and the program drawing into it have to agree on how many columns a character
// occupies, or the program's own padding lands in the wrong place. xterm ships a Unicode 6 table
// and the unicode11 addon adds a 2018 one. Neither is what the programs we host actually pad with,
// which is a current table by way of `string-width`, and it is why an agent's box drawing came out
// one column short on every row holding a check mark. See docs/07-terminal-fidelity.md.
//
// There is no current provider to install, so this generates the difference instead: for every
// codepoint the addon does not call zero width, compare its width against `get-east-asian-width`,
// which is the same data `string-width` reads, and record only the disagreements. It is a small
// table, and `char-width.test.ts` recomputes it to make sure the checked-in copy has not gone stale
// against a newer copy of that data.
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { eastAsianWidth } from 'get-east-asian-width';
import { Unicode11Addon } from '@xterm/addon-unicode11';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'shared/src/char-width-data.ts');

/**
 * The addon's provider, without a terminal to attach it to.
 *
 * `activate` takes the terminal only to reach `unicode.register`, so a stub with that one method
 * hands back the provider itself. Reaching for the table this way keeps the addon as the single
 * source of the zero-width and base-width data rather than copying either.
 */
export function unicode11Provider() {
  let captured = null;
  new Unicode11Addon().activate({ unicode: { register: (p) => (captured = p) } });
  if (captured === null) throw new Error('the unicode11 addon did not register a provider');
  return captured;
}

/** Every codepoint where the 2018 table and the current one disagree, collapsed into ranges. */
export function widthCorrections() {
  const base = unicode11Provider();
  const ranges = [];
  let start = -1;
  let previous = -1;
  let width = 0;
  for (let cp = 0x20; cp <= 0x10ffff; cp++) {
    // Surrogates are never a character in their own right, and asking costs a wrong answer.
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const was = base.wcwidth(cp);
    // Zero width is combining and control behavior rather than an East Asian Width question, so
    // it stays the addon's to decide. Nothing here ever makes a character appear or disappear.
    if (was === 0) continue;
    const now = eastAsianWidth(cp) === 2 ? 2 : 1;
    if (now === was) continue;
    if (start !== -1 && cp === previous + 1 && now === width) {
      previous = cp;
      continue;
    }
    if (start !== -1) ranges.push([start, previous, width]);
    start = cp;
    previous = cp;
    width = now;
  }
  if (start !== -1) ranges.push([start, previous, width]);
  return ranges;
}

const hex = (n) => `0x${n.toString(16).padStart(4, '0')}`;

const ranges = widthCorrections();
const widened = ranges.filter((r) => r[2] === 2).length;

const body = `// Generated by scripts/generate-char-width.mjs. Do not edit by hand.
//
// Where xterm's Unicode 11 table disagrees with the current one, and what the width should be.
// ${String(ranges.length)} ranges, ${String(widened)} of them widening. Regenerate after updating
// get-east-asian-width or @xterm/addon-unicode11, and char-width.test.ts fails if you forget.

/** A closed range of codepoints, and the number of columns they occupy. */
export type WidthRange = readonly [first: number, last: number, width: 1 | 2];

export const WIDTH_CORRECTIONS: readonly WidthRange[] = [
${ranges.map(([a, b, w]) => `  [${hex(a)}, ${hex(b)}, ${String(w)}],`).join('\n')}
];
`;

const config = (await resolveConfig(OUT)) ?? {};
writeFileSync(OUT, await format(body, { ...config, filepath: OUT }));
console.log(`wrote ${String(ranges.length)} ranges to shared/src/char-width-data.ts`);
